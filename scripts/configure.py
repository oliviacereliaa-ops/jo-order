#!/usr/bin/env python3
"""Write settings from .env into the HTML pages.

- GATE_PASSWORD   -> salted PBKDF2 hash for the lock screen (the plain password never goes into the repo).
- APPS_SCRIPT_URL -> default Apps Script web app URL, so nobody has to paste it.

Run again whenever you change either value. A new salt is generated each time,
so everyone has to unlock again.
"""
import hashlib
import json
import os
import re
import secrets
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAGES = ["index.html", "production.html"]
ITERATIONS = 600_000
GATE_LINE = re.compile(r"^const GATE = .*; // @gate.*$", re.M)
URL_LINE = re.compile(r"^const DEFAULT_URL = .*; // @url.*$", re.M)
URL_RE = re.compile(r"^https://script\.google\.com/(?:a/macros/[^/]+|macros)/s/[\w-]+/exec$")


def read_env(path):
    env = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, value = line.split("=", 1)
            env[key.strip()] = value.strip().strip('"').strip("'")
    return env


def main():
    env_path = os.path.join(ROOT, ".env")
    if not os.path.exists(env_path):
        sys.exit("No .env found. Copy .env.example to .env and fill it in.")
    env = read_env(env_path)
    password = env.get("GATE_PASSWORD", "")
    if not password:
        sys.exit("GATE_PASSWORD is empty in .env.")
    url = env.get("APPS_SCRIPT_URL", "")
    if url and not URL_RE.match(url):
        sys.exit("APPS_SCRIPT_URL must look like https://script.google.com/macros/s/.../exec")

    salt = secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, ITERATIONS)
    gate = json.dumps({"salt": salt.hex(), "iter": ITERATIONS, "hash": digest.hex()})
    lines = (
        (GATE_LINE, f"const GATE = {gate}; // @gate: generated by scripts/configure.py, do not edit by hand", "@gate"),
        (URL_LINE, f"const DEFAULT_URL = {json.dumps(url)}; // @url: generated by scripts/configure.py from APPS_SCRIPT_URL", "@url"),
    )

    for page in PAGES:
        path = os.path.join(ROOT, page)
        with open(path, encoding="utf-8") as f:
            html = f.read()
        for pattern, new, tag in lines:
            html, n = pattern.subn(lambda _: new, html)
            if n != 1:
                sys.exit(f"{page}: expected one '{tag}' line, found {n}.")
        with open(path, "w", encoding="utf-8") as f:
            f.write(html)
        print(f"updated {page}")


if __name__ == "__main__":
    main()
